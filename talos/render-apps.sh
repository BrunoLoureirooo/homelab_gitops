#!/usr/bin/env bash
# Generate the Talos cluster's Argo CD app set from the live repo's (plan 15-03).
#
#   render-apps.sh [--apps-out DIR] [--manifests-out DIR] [--force]
#
# Reads argocd/apps/*.yaml (never edits it) and talos/apps-overrides.yaml, and writes
#   <apps-out>/            default talos/apps       one Application per app
#   <manifests-out>/<app>/ default talos/manifests  generated manifest copies
# plus every Talos-only Application in talos/apps-src/*.yaml. The output is
# deterministic; an existing non-empty output needs --force. Needs yq (mikefarah
# v4). Portable to bash 3.2.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="${TALOS_REPO_ROOT:-$(cd "$here/.." && pwd)}"
over="${TALOS_OVERRIDES:-$here/apps-overrides.yaml}"
apps_out="$here/apps"
man_out="$here/manifests"
force=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --apps-out)
      apps_out="${2:?--apps-out needs a directory}"
      shift 2
      ;;
    --manifests-out)
      man_out="${2:?--manifests-out needs a directory}"
      shift 2
      ;;
    --force)
      force=1
      shift
      ;;
    *)
      echo "usage: render-apps.sh [--apps-out DIR] [--manifests-out DIR] [--force]" >&2
      exit 64
      ;;
  esac
done

command -v yq >/dev/null || {
  echo "render-apps: yq (mikefarah v4) is required" >&2
  exit 2
}
[[ -f "$over" ]] || {
  echo "render-apps: no overrides file $over" >&2
  exit 2
}

storage="$(yq -r '.storage // ""' "$over")"
[[ "$storage" == local-path || "$storage" == topolvm ]] || {
  echo "render-apps: storage in $over must be local-path or topolvm (got '$storage')" >&2
  exit 2
}

if [[ -d "$apps_out" && -n "$(ls -A "$apps_out" 2>/dev/null)" && "$force" -ne 1 ]]; then
  echo "render-apps: $apps_out is not empty; use --force to regenerate it" >&2
  exit 2
fi
mkdir -p "$apps_out" "$man_out"
if [[ "$force" -eq 1 ]]; then
  find "$apps_out" -mindepth 1 -maxdepth 1 -name '*.yaml' -delete
fi

excluded() { # excluded <app>
  local a="$1" e
  if [[ "$a" == topolvm ]]; then
    [[ "$storage" == topolvm ]] && return 1
    return 0
  fi
  while IFS= read -r e; do
    [[ "$e" == "$a" ]] && return 0
  done < <(yq -r '(.exclude // [])[]' "$over")
  return 1
}

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# --- the repo's Applications, with overrides -------------------------------------
for f in "$root"/argocd/apps/*.yaml; do
  [[ -f "$f" ]] || continue
  name="$(yq -r '.metadata.name' "$f")"
  excluded "$name" && continue
  tmp="$work/$(basename "$f")"
  cp "$f" "$tmp"

  newpath="$(yq -r ".path.\"$name\" // \"\"" "$over")"
  if [[ -n "$newpath" ]]; then
    yq -i ".spec.source.path = \"$newpath\"" "$tmp"
  fi
  while IFS= read -r vf; do
    [[ -n "$vf" ]] || continue
    yq -i "(.spec.sources[] | select(has(\"chart\")) | .helm.valueFiles) += [\"\$values/$vf\"]" "$tmp"
  done < <(yq -r "(.extra_valuefiles.\"$name\" // [])[]" "$over")

  # A rename (overrides `rename:`) changes the Application's name and the file
  # name; the source stays argocd/apps/<original>.yaml. Used where the original
  # file name would be caught by talos/.gitignore (`secrets.yaml`).
  newname="$(yq -r ".rename.\"$name\" // \"\"" "$over")"
  outfile="$(basename "$f")"
  if [[ -n "$newname" ]]; then
    yq -i ".metadata.name = \"$newname\"" "$tmp"
    outfile="$newname.yaml"
  fi
  {
    echo "# GENERATED by talos/render-apps.sh from argocd/apps/$(basename "$f"); do not edit"
    cat "$tmp"
  } >"$apps_out/$outfile"
done

# --- Talos-only Applications --------------------------------------------------------
for f in "$here"/apps-src/*.yaml; do
  [[ -f "$f" ]] || continue
  # the local-path provisioner exists only under the local-path storage verdict
  if [[ "$(basename "$f")" == local-path-provisioner.yaml && "$storage" == topolvm ]]; then
    continue
  fi
  {
    echo "# GENERATED by talos/render-apps.sh from talos/apps-src/$(basename "$f"); do not edit"
    cat "$f"
  } >"$apps_out/$(basename "$f")"
done

# --- generated manifest copies --------------------------------------------------------
while IFS= read -r app; do
  [[ -n "$app" ]] || continue
  from="$root/$(yq -r ".manifest_copies.\"$app\".from" "$over")"
  [[ -d "$from" ]] || {
    echo "render-apps: no source directory $from for $app" >&2
    exit 2
  }
  dst="$man_out/$app"
  rm -rf "$dst"
  mkdir -p "$dst"
  case "$app" in
    cluster-baseline)
      # local-path-config.yaml is the k3s add-on ConfigMap of the old cluster: not carried over.
      for m in "$from"/*.yaml; do
        [[ "$(basename "$m")" == local-path-config.yaml ]] && continue
        cp "$m" "$dst/"
      done
      # The homeserver namespace allows privileged pods (Jellyfin's /dev/dri hostPath).
      yq -i 'select(.kind == "Namespace" and .metadata.name == "homeserver") |= (.metadata.labels."pod-security.kubernetes.io/enforce" = "privileged")' "$dst/namespace-storage.yaml"
      if [[ "$storage" == local-path ]]; then
        # Same StorageClass NAME, different provisioner: PVCs, values and Velero keep topolvm-fast.
        yq -i 'select(.kind == "StorageClass" and .metadata.name == "topolvm-fast") |= (.provisioner = "rancher.io/local-path" | del(.parameters) | .allowVolumeExpansion = false)' "$dst/namespace-storage.yaml"
        # Velero fs-backup cannot see hostPath volumes (the provisioner default); `local` PVs are mounted
        # under the pod and are supported, so restores into these volumes work.
        yq -i 'select(.kind == "StorageClass" and .metadata.name == "topolvm-fast") |= (.metadata.annotations.defaultVolumeType = "local")' "$dst/namespace-storage.yaml"
      fi
      for m in "$dst"/*.yaml; do
        tmp="$work/m.yaml"
        {
          echo "# GENERATED by talos/render-apps.sh from $(yq -r ".manifest_copies.\"$app\".from" "$over")/$(basename "$m"); do not edit"
          cat "$m"
        } >"$tmp"
        mv "$tmp" "$m"
      done
      # Talos-only extras (no k3s counterpart): talos/manifests-src/<app>/*.yaml.
      for m in "$here/manifests-src/$app"/*.yaml; do
        [[ -f "$m" ]] || continue
        {
          echo "# GENERATED by talos/render-apps.sh from talos/manifests-src/$app/$(basename "$m"); do not edit"
          cat "$m"
        } >"$dst/$(basename "$m")"
      done
      ;;
    *)
      echo "render-apps: no transformation known for manifest copy '$app'" >&2
      exit 2
      ;;
  esac
done < <(yq -r '.manifest_copies | keys | .[]' "$over" 2>/dev/null)

echo "render-apps: wrote $(find "$apps_out" -maxdepth 1 -name '*.yaml' | wc -l | tr -d ' ') Applications to $apps_out (storage=$storage)"
