#!/usr/bin/env bash
# Build the Talos overlay for immich-infra into the directory the Talos Application
# points at (plan 15-06 Task 4).
#
#   render.sh            write talos/manifests/immich-infra/immich-infra.yaml
#   render.sh --check    exit 1 if the committed file differs from a fresh build
#
# The base (argocd/manifests/immich-infra) is only READ. Needs `kubectl` (its built-in
# kustomize) or a `kustomize` binary.
set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
overlay="$repo/talos/overlays/immich-infra"
outdir="$repo/talos/manifests/immich-infra"
out="$outdir/immich-infra.yaml"

build() {
  if command -v kustomize >/dev/null 2>&1; then
    kustomize build --load-restrictor LoadRestrictionsNone "$overlay"
  else
    kubectl kustomize --load-restrictor LoadRestrictionsNone "$overlay"
  fi
}

header='# GENERATED by talos/overlays/render.sh from talos/overlays/immich-infra (base:
# argocd/manifests/immich-infra). Do not edit by hand; run render.sh and commit the result.
# check-backups-06.sh fails when this file differs from a fresh build.'

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
{
  echo "$header"
  build
} >"$tmp"

if [[ "${1:-}" == "--check" ]]; then
  if [[ -f "$out" ]] && diff -q "$tmp" "$out" >/dev/null; then
    echo "OK: $out is current"
    exit 0
  fi
  echo "DRIFT: $out differs from a fresh build (run talos/overlays/render.sh)"
  exit 1
fi

mkdir -p "$outdir"
cp "$tmp" "$out"
echo "wrote $out"
